/** Lists and reads account-scoped transcripts from oma-agent's native Hermes session store. */

import { createHash } from "node:crypto";
import { z } from "zod";

import type { ChatToolCall } from "../agent-activity";
import { type ChatHistory, type ChatTranscript } from "../agent-chat";
import { getDb } from "../db";
import { AgentChatError, getAgentRun, readAgentSessionActivity, readAgentSessionApi, scopedAgentSessionId, startAgentRun } from "./agent-chat";
import { workspaceId } from "./agent-workspace";
import { projectSetupIntro, readProjectSetup } from "./project-setup";

const id = z.uuid();
const newTurn = z.object({ threadId: id, turnId: id, message: z.string(), campaignId: workspaceId.optional() });
const maxHistoryOffset = 1_000_000;
const offsetValue = z.number().int().min(0).max(maxHistoryOffset);
const sessions = z.object({
  data: z.array(z.object({ id: z.string(), _lineage_root_id: z.string().nullish(), title: z.string().nullish(), preview: z.string().nullish() })),
  has_more: z.boolean().optional(),
});
const transcript = z.object({
  data: z.array(z.object({
    id: z.union([z.number(), z.string()]),
    session_id: z.string().optional().catch(undefined),
    role: z.string(),
    content: z.string().nullish().catch(undefined),
    display_content: z.string().nullish().catch(undefined),
    display_kind: z.string().nullish().catch(undefined),
    tool_name: z.string().regex(/^[\w.-]{1,96}$/).optional().catch(undefined),
    tool_call_id: z.string().regex(/^[\w.-]{1,128}$/).optional().catch(undefined),
    tool_calls: z.array(z.unknown()).nullable().optional().catch(undefined),
  })),
});
const messagePageSize = 80;
const recordedToolLimit = 12;
const sessionPageSize = 200;
const hermesNotificationFooter = "\n\n[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. "
  + "Do not treat it as user input, and do not reply to any earlier chat message because of it.]";

function sessionPrefix(userId: string, campaignId?: string) {
  // The session namespace stays stable when the console signing key is rotated.
  const scope = createHash("sha256").update(JSON.stringify([userId, campaignId ?? null])).digest("hex").slice(0, 32);
  return "oma_" + scope + "_";
}

/** Read only ownership links from the retired console schema. Hermes supplies all transcript content. */
function legacySessions(userId: string, campaignId?: string) {
  const db = getDb();
  if (!db.prepare("SELECT 1 FROM sqlite_schema WHERE type = 'table' AND name = 'chat_threads'").get()) return [];
  const rows = db.prepare("SELECT id, session_id FROM chat_threads WHERE user_id = ? AND campaign_id IS ?")
    .all(userId, campaignId ?? null) as { id: string; session_id: string }[];
  return rows.filter((row) => id.safeParse(row.id).success && id.safeParse(row.session_id).success);
}

/** The private VM activity service uses the same roots as the account’s chat history. */
export function campaignChatScope(userId: string, campaignId: string) {
  return {
    chatPrefix: sessionPrefix(userId, campaignId),
    legacySessions: legacySessions(userId, campaignId).map((row) => row.session_id),
  };
}

function projectChat(userId: string, campaignId?: string) {
  if (campaignId) return;
  const project = readProjectSetup(userId);
  if (project?.setup.status !== "done" || !project.delivery?.runHandle) return;
  const { sessionId, runHandle } = project.delivery;
  const { websiteUrl, githubUrl } = project.setup;
  const links = [websiteUrl && `Website: ${websiteUrl}`, githubUrl && `GitHub: ${githubUrl}`].filter(Boolean).join("\n");
  return { sessionId, runHandle, links };
}

function resolveSessionId(userId: string, threadId: string, campaignId?: string, setup = projectChat(userId, campaignId)) {
  if (setup?.sessionId === threadId) return setup.sessionId;
  return legacySessions(userId, campaignId).find((row) => row.id === threadId)?.session_id
    ?? sessionPrefix(userId, campaignId) + threadId.toLowerCase();
}

export async function sendNativeChatTurn(userId: string, input: unknown) {
  const parsed = newTurn.safeParse(input);
  if (!parsed.success) throw new AgentChatError(422, "Enter a valid chat message and try again.");
  const { threadId, turnId, message, campaignId } = parsed.data;
  return startAgentRun(userId, {
    sessionId: resolveSessionId(userId, threadId, campaignId), turnId, message, campaignId,
  }, "default");
}

async function readTranscript(sessionId: string, offset: number, campaignId?: string, setup?: ReturnType<typeof projectChat>): Promise<ChatTranscript> {
  const campaignSuffix = campaignId ? "\n\nCampaign ID: " + campaignId : "";
  const messages: ChatTranscript["messages"] = [];
  const recorded = new Map<string, ChatToolCall>();
  const page = (nextOffset: number | null): ChatTranscript => ({
    messages: messages.reverse(), nextOffset,
    ...(recorded.size ? { recordedTools: [...recorded.values()].reverse() } : {}),
  });
  const limit = messagePageSize + 1;
  // Hermes counts raw rows and returns each latest-first page in chronological order.
  // Seek one extra visible message; internal rows alone cannot make an older page.
  for (let cursor = offset; cursor <= maxHistoryOffset; cursor += limit) {
    let response;
    try {
      response = await readAgentSessionApi("/" + sessionId + "/messages?order=latest&include_compacted=true&limit="
        + limit + "&offset=" + cursor);
    } catch (error) {
      if (!(error instanceof AgentChatError && error.status === 404 && offset === 0)) throw error;
      if (cursor === 0 && setup?.links) messages.push({ id: "project-links", role: "user", text: setup.links });
      break;
    }
    const { payload, redact } = response;
    const parsed = transcript.safeParse(payload);
    if (!parsed.success) throw new AgentChatError(502, "oma-agent returned an invalid chat transcript.");
    const rows = parsed.data.data;
    for (let index = rows.length - 1; index >= 0; index--) {
      const row = rows[index];
      // Tool rows do not count toward chat paging. Only project names and opaque IDs;
      // a persisted result is not a reliable signal of either success or live execution.
      if (offset === 0 && recorded.size < recordedToolLimit && row.role === "tool" && row.display_kind !== "hidden"
          && row.tool_name && redact(row.tool_name) === row.tool_name) {
        const callId = row.tool_call_id && redact(row.tool_call_id) === row.tool_call_id ? row.tool_call_id : undefined;
        const key = callId ?? `row:${cursor + rows.length - 1 - index}`;
        if (!recorded.has(key)) recorded.set(key, { id: key, name: row.tool_name, status: "recorded" });
      }
      if ((row.role !== "user" && row.role !== "assistant") || typeof row.content !== "string"
        || row.display_kind === "hidden" || (row.tool_calls?.length && row.display_kind !== "commentary")) continue;
      if (row.role === "user" && row.content.startsWith("[OMA_INTERNAL_DELEGATION_WAKE_V1] The gateway saved a background delegation result above.")) continue;
      const projectLinks = setup?.links && row.role === "user" && row.content.startsWith(projectSetupIntro);
      // Hermes marks API admissions internal even for ordinary user text. Background
      // notices either have a dedicated display kind or carry Hermes's exact footer.
      const markedNotice = row.role === "user" && row.display_kind === "internal_notification"
        && row.content.trimEnd().endsWith(hermesNotificationFooter);
      const isNotice = row.display_kind === "async_delegation_complete" || row.display_kind === "process_complete"
        || row.display_kind?.startsWith("notification") || markedNotice;
      const role = projectLinks ? "user" : isNotice ? "notification" : row.role;
      const content = markedNotice ? row.content.trimEnd().slice(0, -hermesNotificationFooter.length)
        : row.role === "user" && row.display_kind === "steer" ? row.display_content ?? row.content : row.content;
      const text = projectLinks ? setup.links : role === "user" && campaignSuffix && content.endsWith(campaignSuffix)
        ? content.slice(0, -campaignSuffix.length) : content;
      if (!text.trim()) continue;
      if (messages.length === messagePageSize) {
        const next = cursor + rows.length - 1 - index;
        return page(next <= maxHistoryOffset ? next : null);
      }
      messages.push({ id: projectLinks ? "project-links" : (row.session_id ?? sessionId) + ":" + row.id, role, text: redact(text) });
    }
    if (rows.length < limit) break;
  }
  return page(null);
}

export async function loadOlderChatMessages(userId: string, threadId: unknown, offset: unknown, campaignId?: string) {
  const input = z.object({ threadId: id, offset: offsetValue, campaignId: workspaceId.optional() }).safeParse({ threadId, offset, campaignId });
  if (!input.success) throw new AgentChatError(422, "Invalid chat history request.");
  const setup = projectChat(userId, campaignId);
  return readTranscript(resolveSessionId(userId, input.data.threadId, campaignId, setup), input.data.offset, campaignId,
    setup?.sessionId === input.data.threadId ? setup : undefined);
}

export async function readChatSession(userId: string, threadId: unknown, campaignId?: unknown) {
  const input = z.object({ threadId: id, campaignId: workspaceId.optional() }).safeParse({ threadId, campaignId });
  if (!input.success) throw new AgentChatError(422, "Invalid chat session.");
  const project = projectChat(userId, input.data.campaignId);
  const setup = project?.sessionId === input.data.threadId ? project : undefined;
  const session = resolveSessionId(userId, input.data.threadId, input.data.campaignId, project);
  const [page, activity] = await Promise.all([
    readTranscript(session, 0, input.data.campaignId, setup), readAgentSessionActivity(userId, session),
  ]);
  // The setup receipt is saved before every gateway version exposes the run in session activity.
  if (!activity.handle && setup) {
    try {
      const run = await getAgentRun(userId, setup.runHandle, "default");
      if (run.status === "running") activity.handle = setup.runHandle;
    } catch (error) {
      if (!(error instanceof AgentChatError && error.status === 404)) throw error;
    }
  }
  return { ...page, ...activity };
}

export async function loadChatHistory(userId: string, campaignId?: string, selected?: string | string[]): Promise<ChatHistory> {
  const chats: ChatHistory["chats"] = [];
  const setup = projectChat(userId, campaignId);
  try {
    const prefix = sessionPrefix(userId, campaignId);
    const known = new Map(legacySessions(userId, campaignId).map((row) => [row.session_id, row.id]));
    if (setup) known.set(setup.sessionId, setup.sessionId);
    const seen = new Set<string>();
    for (let offset = 0; offset <= 1_000_000; offset += sessionPageSize) {
      const { payload, redact } = await readAgentSessionApi("?source=api_server&limit=" + sessionPageSize + "&offset=" + offset);
      const page = sessions.safeParse(payload);
      if (!page.success) throw new AgentChatError(502, "oma-agent returned an invalid list of conversations.");
      for (const row of page.data.data) {
        const root = row._lineage_root_id ?? row.id;
        const threadId = known.get(root) ?? known.get(row.id) ?? (root.startsWith(prefix) ? scopedAgentSessionId.exec(root)?.[1] : undefined);
        if (!threadId || !id.safeParse(threadId).success || seen.has(threadId)) continue;
        seen.add(threadId);
        const label = (row.title || row.preview || "Conversation").replace(/\s+/g, " ").trim();
        chats.push({ id: threadId, title: threadId === setup?.sessionId ? "Project setup" : redact(label).slice(0, 80) || "Conversation" });
      }
      if (!page.data.data.length || !(page.data.has_more ?? page.data.data.length >= sessionPageSize)) break;
    }

    if (setup && !seen.has(setup.sessionId)) chats.unshift({ id: setup.sessionId, title: "Project setup" });
    const requested = id.safeParse(selected);
    const active = selected === "new" ? undefined : selected === "setup" ? setup?.sessionId : requested.success ? requested.data : chats[0]?.id;
    if (setup && active === setup.sessionId) {
      const { handle, messages, nextOffset, recordedTools } = await readChatSession(userId, active);
      return { chats, active: { id: active, handle, messages, nextOffset, recordedTools, isProjectSetup: true } };
    }
    return active ? { chats, active: { id: active, ...await readTranscript(resolveSessionId(userId, active, campaignId, setup), 0, campaignId) } }
      : { chats };
  } catch (error) {
    if (!(error instanceof AgentChatError)) throw error;
    return { chats, error: "Couldn’t load conversation history from oma-agent. " + error.message };
  }
}
